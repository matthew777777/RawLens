#!/usr/bin/env python3
"""Derive the D65 linear-sRGB -> S-Gamut3.Cine matrix; no third-party modules.

Sony Technical Summary for S-Gamut3.Cine/S-Log3, v1.00, last page:
https://www.sony.jp/ls-camera/knowledge/pdf/TechnicalSummary_for_S-Gamut3Cine_S-Gamut3_S-Log3_V1_00.pdf
RGB xy: (.766,.275), (.225,.800), (.089,-.087); D65 (.3127,.3290).
sRGB xy are ITU-R BT.709-6 table 1. Both whites are identical: no CAT.
Run after editing these primaries, then rebuild the affected SPIR-V assets.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def mul(a, b):
    return [[sum(a[r][k] * b[k][c] for k in range(3)) for c in range(3)] for r in range(3)]


def inverse(m):
    a = [row[:] + [float(i == j) for j in range(3)] for i, row in enumerate(m)]
    for i in range(3):
        pivot = max(range(i, 3), key=lambda r: abs(a[r][i]))
        a[i], a[pivot] = a[pivot], a[i]
        scale = a[i][i]
        a[i] = [x / scale for x in a[i]]
        for j in range(3):
            if j != i:
                scale = a[j][i]
                a[j] = [x - scale * y for x, y in zip(a[j], a[i])]
    return [row[3:] for row in a]


def rgb_to_xyz(primaries):
    columns = [[x / y, 1., (1 - x - y) / y] for x, y in primaries]
    m = [list(row) for row in zip(*columns)]
    white = [[.3127 / .3290, 1., (1 - .3127 - .3290) / .3290]]
    scale = mul(inverse(m), [[v] * 3 for v in white[0]])
    return [[m[r][c] * scale[c][0] for c in range(3)] for r in range(3)]


MATRIX = mul(inverse(rgb_to_xyz([(.766, .275), (.225, .800), (.089, -.087)])),
             rgb_to_xyz([(.64, .33), (.30, .60), (.15, .06)]))

if __name__ == '__main__':
    rows = [', '.join(f'{x:.10f}' for x in row) for row in MATRIX]
    kt = ROOT / 'app/src/main/java/com/matthew/rawlens/SonyGamut.kt'
    kt.write_text('''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/generate_sgamut3_cine.py from Sony's published primaries.
package com.matthew.rawlens

internal object SonyGamut {
    // Row-major; signed scene-linear input and output. Do not clip here.
    private val fromLinearSrgb = arrayOf(
''' + ',\n'.join('        floatArrayOf(' + ', '.join(f'{x:.10f}f' for x in row) + ')' for row in MATRIX) + '''
    )

    private val toLinearSrgb = arrayOf(
''' + ',\n'.join('        floatArrayOf(' + ', '.join(f'{x:.10f}f' for x in row) + ')' for row in inverse(MATRIX)) + '''
    )

    fun fromLinearSrgb(rgb: FloatArray) = transform(fromLinearSrgb, rgb)
    fun toLinearSrgb(rgb: FloatArray) = transform(toLinearSrgb, rgb)
    fun inverseRow(row: Int) = toLinearSrgb[row].copyOf()

    private fun transform(matrix: Array<FloatArray>, rgb: FloatArray): FloatArray {
        require(rgb.size == 3)
        return FloatArray(3) { r -> matrix[r].indices.sumOf { c ->
            (matrix[r][c] * rgb[c]).toDouble()
        }.toFloat() }
    }
}
''')
    paths = list((ROOT / 'app/src/main/assets/shaders/vf').glob('*.comp'))
    paths += [ROOT / 'app/src/main/assets/shaders/rcd_packed/rcd_output_yuv.comp']
    for path in paths:
        text = path.read_text()
        if 'slog3cutY' not in text:
            continue
        half = 'float16_t slog3cutY' in text
        typ = 'f16vec3' if half else 'vec3'
        suffix = 'hf' if half else ''
        block = '// BEGIN generated Sony gamut (tools/generate_sgamut3_cine.py)\n'
        block += f'{typ} srgbToSgamut3Cine({typ} v) {{\n    return {typ}('
        block += ',\n        '.join(f'dot(v, {typ}(' + ', '.join(f'{x:.10f}{suffix}' for x in row) + '))' for row in MATRIX)
        block += ');\n}\n// END generated Sony gamut\n'
        if '// BEGIN generated Sony gamut' in text:
            text = re.sub(r'// BEGIN generated Sony gamut.*?// END generated Sony gamut\n', block, text, flags=re.S)
        else:
            start = text.index(('float16_t' if half else 'float') + ' slog3cutY')
            text = text[:start] + block + '\n' + text[start:]
        path.write_text(text)
